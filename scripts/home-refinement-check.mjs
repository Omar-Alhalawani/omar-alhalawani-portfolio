import fs from 'node:fs';
import assert from 'node:assert/strict';
import {launchQABrowser,startQAServer} from './qa-runtime.mjs';
const server=await startQAServer(),browser=await launchQABrowser();
const out='docs/home-refinement';fs.mkdirSync(out,{recursive:true});
const results={};
try{
 const page=await browser.newPage({viewport:{width:1440,height:960}});
 await page.addInitScript(()=>{window.__PORTFOLIO_PROFILE__={frames:[],scenes:{}};window.__refinementToken='preserved';});
 await page.goto(server.url);
 await page.waitForFunction(()=>document.querySelector('[data-scene="hero"]')?.dataset.state==='ready',null,{timeout:60000});
 assert.equal(await page.locator('#engineering-stack').count(),0);
 assert.equal(await page.locator('.world-window').evaluate(el=>getComputedStyle(el).position),'relative');
 await page.mouse.move(1300,250);await page.waitForTimeout(500);
 const pose=await page.evaluate(()=>window.__PORTFOLIO_PROFILE__.scenes.hero.pose);
 assert.ok(pose[3]>.1);assert.equal(pose[5],0);
 await page.mouse.move(10,950);await page.waitForTimeout(800);
 await page.screenshot({path:`${out}/desktop.jpg`,type:'jpeg',quality:85});
 await page.evaluate(()=>window.scrollTo({top:180,behavior:'instant'}));await page.waitForTimeout(300);
 assert.equal(await page.evaluate(()=>window.__PORTFOLIO_PROFILE__.scenes.hero.pose[5]),0);
 results.hero='Anchored; local pointer response and scroll-independent pose confirmed';
 const pending=await page.locator('.home-about').getAttribute('data-reveal-state');assert.equal(pending,'pending');
 await page.locator('.home-about').evaluate(el=>window.scrollTo({top:el.getBoundingClientRect().top+scrollY-100,behavior:'instant'}));
 await page.waitForFunction(()=>document.querySelector('.home-about')?.dataset.revealState==='visible',null,{timeout:15000});
 assert.equal(await page.locator('.home-about').getAttribute('data-reveal-state'),'visible');
 results.reveal='20px / 600ms one-time reveal activates';
 await page.locator('.home-projects').evaluate(el=>window.scrollTo({top:el.getBoundingClientRect().top+scrollY-100,behavior:'instant'}));
 await page.waitForFunction(()=>document.querySelector('[data-scene="floorplan"]')?.dataset.state==='ready',null,{timeout:60000});
 await page.locator('[data-project="fifo"]').hover();
 await page.locator('[data-project-world] a[href="/projects/fifo"]').first().click();
 await page.waitForURL('**/projects/fifo');
 await page.waitForFunction(()=>document.querySelector('[data-scene="fifo"]')?.dataset.state==='ready',null,{timeout:60000});
 assert.equal(await page.evaluate(()=>window.__refinementToken),'preserved');
 await page.waitForFunction(()=>!document.querySelector('.project-handoff'),null,{timeout:30000});
 results.projects='Platform selection and one FIFO transition passed; same document retained';
 await page.goto(`${server.url}/contact`);
 await page.waitForFunction(()=>document.querySelector('[data-scene="contact"]')?.dataset.state==='ready',null,{timeout:60000});
 const globe=page.locator('[data-scene="contact"] canvas'),rect=await globe.boundingBox();
 const before=await page.evaluate(()=>window.__PORTFOLIO_PROFILE__.scenes.contact.rotation);
 await page.mouse.move(rect.x+rect.width/2,rect.y+rect.height/2);await page.mouse.down();await page.mouse.move(rect.x+rect.width/2+100,rect.y+rect.height/2,{steps:8});await page.mouse.up();await page.waitForTimeout(300);
 const after=await page.evaluate(()=>window.__PORTFOLIO_PROFILE__.scenes.contact.rotation);assert.notDeepEqual(before,after);
 results.contact='Globe renders and drag rotation works';
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 await mobile.goto(server.url);await mobile.waitForFunction(()=>document.querySelector('[data-scene="hero"]')?.dataset.state==='ready',null,{timeout:60000});
 assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await mobile.screenshot({path:`${out}/mobile.jpg`,type:'jpeg',quality:85});
 results.mobile='390px viewport has no horizontal overflow; hero and copy render';
 await mobile.close();
 const reduced=await browser.newPage({viewport:{width:1440,height:960},reducedMotion:'reduce'});
 await reduced.goto(server.url);
 assert.equal(await reduced.locator('[data-reveal-state="pending"]').count(),0);
 assert.equal(await reduced.locator('.technical-energy').evaluate(el=>getComputedStyle(el).animationName),'none');
 results.reducedMotion='No hidden reveal content or background animation';
 await reduced.close();await page.close();
 fs.writeFileSync(`${out}/checks.json`,JSON.stringify(results,null,2)+'\n');console.log(results);
}finally{await browser.close();await server.close();}
